import assert from 'node:assert/strict';
import { newSession, recordLearner, skillState } from '../src/models.ts';
import { BrowserLearningRepository, validStore } from '../src/repository.ts';
const memory=new Map();
globalThis.localStorage={getItem:key=>memory.get(key)||null,setItem:(key,value)=>memory.set(key,value)};
const repository=new BrowserLearningRepository();
const original=repository.load();
assert.equal(original.courses.length,0,'no fabricated student data');
const course={id:'analysis',name:'Real Analysis',description:'',createdAt:Date.now()};
const session=newSession(course.id);
let data={...original,courses:[course],sessions:[session]};
const module={id:'cauchy',title:'Cauchy condition',purpose:'Control late terms.',dependsOn:[]};
const history=Array.from({length:5},(_,i)=>({question:{moduleId:'cauchy',skill:'Cauchy condition',prompt:`Question ${i}`,options:['1','2','3','4','5'],correctAnswer:'A'},choice:'A',reasoning:'',feedback:'Sound',explanation:'',isCorrect:true,reasoningSound:true,time:Date.now()+i,stage:'diagnostic'}));
const messages=[{id:'problem-1',role:'student',kind:'problem',text:'Prove convergence.',createdAt:1},{id:'question-1',role:'tutor',kind:'question',question:history[0].question,createdAt:2}];
data=recordLearner(data,session.id,{modules:[module],history,messages,currentQuestion:history[0].question,stage:'diagnostic',draftReasoning:'Unsent thought',draftFeedback:'Please clarify the quantifiers.'});
assert.equal(data.evidence.length,5);
assert.equal(data.skills.length,1);
assert.equal(skillState(data.evidence).status,'Developing','one narrow context does not establish strong evidence');
data=recordLearner(data,session.id,data.sessions[0].learner);
assert.equal(data.evidence.length,5,'autosaving never duplicates observations');
const second=newSession(course.id);data={...data,sessions:[...data.sessions,second]};
data=recordLearner(data,second.id,{modules:[module],history:[{...history[0],time:Date.now()+9}]});
assert.equal(data.skills.length,1,'course skill identity is shared between sessions');
assert.equal(skillState(data.evidence).status,'Strong evidence');
const other={...course,id:'information',name:'Information Theory'};const separate=newSession(other.id);
data={...data,courses:[...data.courses,other],sessions:[...data.sessions,separate]};
data=recordLearner(data,separate.id,{modules:[module],history:[]});
assert.equal(data.skills.length,2,'skill identity never crosses courses');
assert.equal(skillState([]).status,'Not assessed');
assert.equal(skillState(data.evidence,Date.now()+22*86400000).status,'Needs review');
repository.save(data);const loaded=repository.load();
assert.equal(loaded.sessions[0].learner.draftReasoning,'Unsent thought');
assert.equal(loaded.sessions[0].learner.draftFeedback,'Please clarify the quantifiers.');
assert.deepEqual(loaded.sessions[0].learner.messages,messages,'the chronological conversation survives save and reload');
assert.equal(loaded.sessions.length,3);
assert(validStore(loaded));assert(!validStore({version:1}));
assert.equal(loaded.sessions[1].learner.stage,undefined,'prior evidence does not auto-advance a fresh session');
const uncertain=recordLearner(data,second.id,{modules:[module],history:[{...history[0],choice:'F',isCorrect:false,time:Date.now()+10}]});
assert.equal(uncertain.evidence.at(-1).correct,null,'I do not know is uncertainty, not a wrong assessed answer');
memory.clear();memory.set('math-mastery-anonymous-profile','old');memory.set('math-mastery-progress-old',JSON.stringify({theorem:'Original problem',modules:[module],history}));
const migrated=repository.load();assert.equal(migrated.sessions[0].learner.theorem,'Original problem');assert(memory.has('math-mastery-progress-old'),'legacy original remains untouched');
repository.save({...migrated,revision:3});assert.throws(()=>repository.save({...migrated,revision:2}),/Another tab/);
console.log('PASS: multi-course persistence, draft resume, evidence deduplication, skill identity, uncertainty, review, migration, and stale-write protection');
const latexTitle=String.raw`Study a very long mathematical problem whose final condition is $x_n\to x$ and prove convergence.`;
const titled=recordLearner({...original,courses:[course],sessions:[session]},session.id,{theorem:latexTitle});
assert.equal(titled.sessions[0].title,latexTitle,'automatic titles must never cut through a LaTeX delimiter');
const reviewed={...titled.sessions[0],phase:6,learner:{...titled.sessions[0].learner,mode:'repetition',returnStage:'diagnostic',currentQuestion:history[0].question,stage:'repetition'}};
const resumed=recordLearner({...titled,sessions:[reviewed]},session.id,{...reviewed.learner,mode:'guided',stage:'diagnostic'});
assert.equal(resumed.sessions[0].phase,2,'leaving retrieval restores the guided workspace');
